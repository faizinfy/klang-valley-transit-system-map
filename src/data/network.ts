// Klang Valley rail + BRT network, transcribed from the
// "Klang Valley Transit System Map" designed by @ziqtofu.
//
// Each line lists its stops in running order. A stop is
//   [code, name]                     – ordinary stop
//   [code, name, { key, status }]    – overrides
// Stops sharing a station key are one physical station (an interchange).
// The key defaults to a slug of the name, so same-named stops merge unless
// a distinct `key` is given. Separate stations joined by a walkway are
// listed in `connections`.
//
// Stop status:
//   provisional – greyed out on the map (future/infill); trains don't stop
//   planned     – opens together with a planned line (e.g. Circle Line)
//
// Notes on deviations from the printed map:
//   - Puchong stops SP19–SP28 are all printed as "SP28"; renumbered in order.
//   - Ara Damansara is printed "KJ25"; it is KJ26.
//   - SunU-Monash is printed "SB4"; it is SB5.
//   - SA11 (Persiaran Hishamuddin) was cancelled and is not on the map.

export type Mode = 'KTM' | 'LRT' | 'MRT' | 'KLIA' | 'Monorail' | 'BRT';
export type LineStatus = 'open' | 'planned' | 'suspended';
export type StopStatus = 'open' | 'provisional' | 'planned';

type StopOpts = { key?: string; status?: StopStatus };
type StopDef = [code: string, name: string, opts?: StopOpts];

export interface LineDef {
  id: string;
  badge: string;
  name: string;
  nameMs: string;
  mode: Mode;
  color: string;
  status: LineStatus;
  note?: string;
  loop?: boolean;
  stops: StopDef[];
}

